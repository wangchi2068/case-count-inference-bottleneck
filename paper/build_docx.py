# ============ 3理论结果与运筹设计 ============
h1('3理论结果与运筹设计')
h2('3.1当期传播参数的条件似然、Fisher信息与方差下界')
body('命题1（当期传播参数的条件似然、Fisher信息与方差）：在个体继发感染条件独立且服从负二项分支模型、二项报告率ρ固定的基准条件下，当n与ρ已知时：')
body('（1）报告病例数C_t在给定(n, R_t)下的边缘分布严格服从负二项分布：C_t|(n,R_t) ~ NB(均值=ρnR_t, 形状参数=nk, p*=k/(k+ρR_t))；')
body('（2）矩估计量 R̂_t = C_t/(ρn) 恰为该条件似然模型下的极大似然估计量（MLE）；当C_t=0时估计量位于参数空间边界；')
body('（3）在内部参数点R_t>0上，关于R_t的Fisher信息量严格等于：')
eq(r'\mathcal{I}(R_t\vert\, n) = \frac{n}{\frac{R_t}{\rho} + \frac{R_t^2}{k}}', 3)
body('（4）估计量R̂_t的条件方差严格达到Cramér–Rao下界：')
eq(r'Var\left(\frac{C_t}{\rho n}\,\vert\, n, R_t\right) = \mathcal{I}(R_t\vert\, n)^{-1} = \frac{R_t}{\rho n} + \frac{R_t^2}{kn}', 4)
body('证明思路：由概率生成函数（PGF），负二项分布在二项抽稀下的复合分布严格保持负二项形式；对其对数似然求导令得分为零直接解得矩估计量；计算得分函数方差即证得Fisher信息量与方差达到CRLB下界。命题1证明了对当期参数而言，信息量随规模n严格线性增长，规模收益恒为正。')

h2('3.2跨期基础水平的边际方差与平滑交叉点')
body('命题2（跨期基础水平的单期边际方差）：在条件矩假设下，若使用单期估计量C_t/(ρn)估计跨期基础水平R̄，其给定n的条件边际方差严格由全方差公式给出：')
eq(r'Var\left(\frac{C_t}{\rho n}\,\vert\, n\right) = v_R + \frac{\bar{R}}{\rho n} + \frac{\bar{R}^2 + v_R}{kn}', 5)
body('定义1（方差占比交叉点）：令m=ρn为上一代风险集对应的期望被报告人数。式(5)可重写为v_R + A/m，其中A = R̄ + ρ(R̄²+v_R)/k。当v_R>0时，定义规模相关方差项A/m与共同环境方差项v_R相等的期望规模为方差占比交叉点：')
eq(r'm_\times = \frac{A}{v_R} = \frac{\bar{R} + \rho(\bar{R}^2 + v_R)/k}{v_R}', 6)
body('在方差分解的代数形式上，m_×处单期估计方差内部信度比（即信号方差占总方差比例）恰好等于0.5。交叉点代表规模项与环境项权重的平滑交接点，而非突变的硬阈值。当m>m_×后，环境方差开始占主导，增加病例数仅能作用于占比逐渐缩小的A/m项。')

h2('3.3监测杠杆的非对称性机制拆解')
body('命题3（监测杠杆的非对称性与超传播方差下界）：将式(5)拆解为关于(n, ρ)的二元函数，并将第二项分解为计数方差与漏报抽稀方差R̄/(ρn) = R̄/n + (1-ρ)R̄/(ρn)。')
body('（1）报告率杠杆的饱和下界：给定有限风险集n<∞，当报告率趋于理想极限ρ→1时：')
