h1('2模型与方法')
h2('2.1传播动力学生灭模型与个体超传播')
body('设时间以代或离散周t推进。上一代真实感染者集合规模为n（风险集）。第i名感染者在当期产生的继发感染数为X_{i,t}。在给定当期环境条件下的传播强度R_t后，假设个体继发感染数服从过离散负二项分支分布：')
eq(r'E[X_{i,t}\vert\, R_t]=R_t,\quad Var(X_{i,t}\vert\, R_t)=R_t+\frac{R_t^2}{k}', 1)
body('其中k>0为个体传播离散度参数（k越小代表超传播异质性越强，k→∞时退化为标准泊松分布）。在给定(n, R_t)条件下，个体继发感染数相互条件独立。当期真实新发感染总数为I_t = ∑X_{i,t}。')

h2('2.2监测漏报与二项抽稀观测模型')
body('现实监测网络无法完全捕获所有真实感染。假设每个真实感染者以概率ρ∈(0,1]独立被报告，当期报告病例数为C_t：')
eq(r'C_t\vert\, I_t \sim Binomial(I_t, \rho)', 2)
body('规范设定声明：在第3节推导中n暂时设定为已知真实风险集规模，其用途是推导物理参照系下的理论基准，并非宣称现实监测已知真实感染数；第3.7节进一步给出仅报告数据可见时的条件方差展开。')

