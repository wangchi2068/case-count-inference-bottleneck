h2('3.4跨期监测预算权衡与AR(1)环境衰减')
body('命题4（预算约束下的监测设计权衡与可行性集合）：设在T个观测期内总监测输入规模预算受限为B = T·m（每期m = ρn_T）：')
body('（1）若各期环境扰动跨期独立，平均估计量的方差为Var(R̄_T) = v_R/T + A/B。总预算B固定时，拉长观测期数T能够以O(1/T)严格单调降低估计方差；')
