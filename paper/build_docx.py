def clean_latex_str(s):
    if not s:
        return ''
    s = s.replace('{', '').replace('}', '')
    replacements = [
        (r"\'o", 'ó'), (r"\'e", 'é'), (r"\'a", 'á'), (r"\'i", 'í'),
        (r"\`e", 'è'), (r"\`a", 'à'), (r"\c{c}", 'c'), (r"\c c", 'c'),
        (r"\O", 'Ø'), (r"\o", 'ø'), (r"\aa", 'å'), (r"\&", '&'),
        (r"$R_t$", 'Rt'), (r"$R_0$", 'R0'), (r"$", ''),
        (r'--', '-'), (r'..', '.')
    ]
    for old, new in replacements:
        s = s.replace(old, new)
    return s.strip()

def load_bib_references():
    bib_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'references.bib')
    with open(bib_path, 'r', encoding='utf-8') as f:
        text = f.read()

    order_keys = [
        'lloydsmith2005superspreading', 'endo2020estimating', 'azmon2014estimating', 'stoner2019hierarchical',
        'rasmussen2011inference', 'dalziel2018urbanization', 'kucharski2020early', 'wallinga2004different',
        'fraser2007estimating', 'cori2013new', 'thompson2019improved', 'gostic2020practical',
        'steyn2025primer', 'nouvellet2018simple', 'bhatt2023semi', 'bracher2021marginal',
        'parag2022quantifying', 'parag2022fundamental', 'parag2025asymmetric', 'engen1998demographic',
        'rohani2002determinism', 'breto2009time', 'aber2025timeseries', 'fuller1987measurement',
        'carroll2006measurement', 'verbeke2000linear', 'armstrong1998effect', 'althouse2015enhancing',
        'reich2019accuracy', 'biggerstaff2018results', 'mathis2024evaluation', 'cramer2022evaluation',
        'ray2023comparing', 'bosse2023scoring', 'zhou2012hospitalizations', 'cochran1977sampling',
        'cdc2026nhsn', 'tokars2018seasonal', 'flaxman2020estimating'
    ]

    entries_map = {}
    for m in re.finditer(r'@(\w+)\{([^,]+),\s*(.*?)\n\}', text, re.DOTALL):
        kind, key, content = m.group(1), m.group(2).strip(), m.group(3)
        entries_map[key] = (kind, content)

    formatted = []
    ordered_entries = [(k, entries_map[k][0], entries_map[k][1]) for k in order_keys if k in entries_map]

    for key, kind, content in ordered_entries:
        fields = {}
        for m in re.finditer(r'(\w+)\s*=\s*\{((?:[^{}]|\{[^{}]*\})*)\}', content):
            fields[m.group(1).lower()] = m.group(2).strip()

        if kind.lower() == 'misc':
            title = clean_latex_str(fields.get('title', ''))
            author = clean_latex_str(fields.get('author', ''))
            year = fields.get('year', '')
            howpub = clean_latex_str(fields.get('howpublished', '').replace(r'\url', ''))
            note = clean_latex_str(fields.get('note', ''))
            formatted.append(f'{author}. {title}. {howpub}, {year}. {note}')
            continue

        raw_authors = fields.get('author', '').split(' and ')
        auth_list = []
        for a in raw_authors:
            a = clean_latex_str(a)
            if ',' in a:
                last, first = a.split(',', 1)
                auth_list.append(f'{last.strip()} {first.strip()}')
            else:
                auth_list.append(a)

        if len(auth_list) > 3:
            authors_str = ', '.join(auth_list[:3]) + ', et al.'
        else:
            authors_str = ', '.join(auth_list) + '.'

        title = clean_latex_str(fields.get('title', '')).rstrip('.')
        year = fields.get('year', '')
        doi = fields.get('doi', '').strip()

        if kind.lower() == 'book':
            publisher = clean_latex_str(fields.get('publisher', ''))
            address = clean_latex_str(fields.get('address', ''))
            edition = fields.get('edition', '')
            ed_str = f'{edition} ed. ' if edition else ''
            pub_str = f'{address}: {publisher}' if address else publisher
            ref_str = f'{authors_str} {title}. {ed_str}{pub_str}, {year}.'
        else:
            journal = clean_latex_str(fields.get('journal', ''))
            vol = fields.get('volume', '')
            num = fields.get('number', '')
            pages = clean_latex_str(fields.get('pages', ''))
            ref_str = f'{authors_str} {title}. {journal}, {year}'
            if vol:
                ref_str += f', {vol}'
                if num:
                    ref_str += f'({num})'
            if pages:
                ref_str += f': {pages}'
            ref_str += '.'

        if doi:
            ref_str += f' DOI: {doi}.'

        formatted.append(ref_str)

    return formatted

